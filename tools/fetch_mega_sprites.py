"""Download real SpriteCollab Mega animations and record attribution. No recoloring or invented forms."""
import json, pathlib, urllib.request, concurrent.futures, subprocess
import fetch_sprites as sprites
ROOT = pathlib.Path(__file__).resolve().parents[1]
REV = '169c79e159b7da274f1492b32948f541dd2441a7'
RAW = f'https://raw.githubusercontent.com/PMDCollab/SpriteCollab/{REV}'
tracker = json.loads(sprites.fetch(RAW + '/tracker.json'))
names = {}
for line in sprites.fetch(RAW + '/credit_names.txt').decode().splitlines()[1:]:
    bits=line.split('\t')
    if len(bits)>1:names[bits[1]]=bits[0]
FORMS=[('mega-charizard-x','0006','0001'),('mega-gengar','0094','0001'),('mega-lucario','0448','0001')]
def download(job):
    key,dex,form=job
    node=tracker[dex]['subgroups'][form]
    url=f'{RAW}/sprite/{dex}/{form}'
    xml=sprites.fetch(url+'/AnimData.xml')
    anims,shadow=sprites.parse_animdata(xml.decode())
    dest=ROOT/'assets'/'pokemon'/key
    normal=sprites.download_set(url,str(dest),anims)
    if not sprites.REQUIRED<=normal.keys():raise RuntimeError('Incomplete form: '+key)
    meta={'s':shadow,'a':normal}
    shiny_node=node.get('subgroups',{}).get('0001',{})
    if sprites.REQUIRED<=shiny_node.get('sprite_files',{}).keys():
        sx=sprites.fetch(url+'/0001/AnimData.xml')
        sa=sprites.parse_animdata(sx.decode())[0] if sx else anims
        shiny=sprites.download_set(url+'/0001',str(dest/'s'),sa,normal)
        if sprites.REQUIRED<=shiny.keys():meta.update(sh=1,sa=shiny)
    credits=[]
    for suffix in ['', '/0001'] if meta.get('sh') else ['']:
        raw=sprites.fetch(url+suffix+'/credits.txt')
        (dest/('credits-shiny.txt' if suffix else 'credits.txt')).write_bytes(raw)
        for line in raw.decode().splitlines():
            parts=line.split('\t')
            if len(parts)>1:credits.append(names.get(parts[1],parts[1]))
    return key,meta,sorted(set(credits))
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:results=list(pool.map(download,FORMS))
(ROOT/'js/data/mega-sprites.js').write_text('/* SpriteCollab Mega form geometry. Generated by tools/fetch_mega_sprites.py. */\nObject.assign(G.SPRITE_META, '+json.dumps({k:m for k,m,c in results},separators=(',',':'))+');\n')
text='# Mega form sprite credits\n\nSource: https://github.com/PMDCollab/SpriteCollab/tree/'+REV+'\n\nImported Charizard X, Gengar and Lucario assets only — license: CC BY-NC 4.0. Sprites are redistributed without changes to their artwork; PNG palette optimization and animation fallback aliases use the existing importer. Raw credits are included beside each form. Pokémon belongs to its respective owners.\n'
for k,m,c in results:text+='\n## '+k+'\n\n'+', '.join(c)+'\n'
text+='\n## mega-venusaur\n\nGenerated normal/shiny artwork. See [generation notes](design/GENERATED-SPRITES.md). This is separate from the SpriteCollab assets above.\n'
text+='\n## gmax-snorlax\n\nGenerated normal/shiny artwork. See [GMAX-SPRITES.md](design/GMAX-SPRITES.md). Separate from SpriteCollab imports.\n'
(ROOT/'docs/MEGA-CREDITS.md').write_text(text)
print('Imported Mega forms:', ', '.join(k for k,m,c in results))
